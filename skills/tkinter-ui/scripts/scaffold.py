def web_code(title, body):
    return f'''"""Generated by the tkinter-ui skill (web look)."""
import os
import sys
from pathlib import Path

candidates = [os.environ.get("TKUI_TKWEBUI_PATH"),
              Path(__file__).resolve().parent / "tkwebui-main",
              Path.cwd() / "tkwebui-main"]
for candidate in candidates:
    if not candidate:
        continue
    candidate = Path(candidate)
    if (candidate / "tkwebui" / "__init__.py").is_file():
        sys.path.insert(0, str(candidate))
        break

import tkinter as tk
from tkinter import ttk
import tkwebui as UI


def main():
    UI.enable_dpi_awareness()
    root = tk.Tk()
    root.title({title!r})
    root.geometry("1000x700")
    UI.apply_theme(root)

    frame = ttk.Frame(root, padding=24)
    frame.pack(fill="both", expand=True)
{body}
    root.mainloop()


if __name__ == "__main__":
    main()
'''


def win11_code(title, body):
    return f'''"""Generated by the tkinter-ui skill (Windows 11 look)."""
import os
import sys
from pathlib import Path

candidates = [os.environ.get("TKUI_TKWIN11_PATH"),
              Path(__file__).resolve().parent / "tkwin11-main",
              Path.cwd() / "tkwin11-main"]
for candidate in candidates:
    if not candidate:
        continue
    candidate = Path(candidate)
    if (candidate / "tkwin11" / "__init__.py").is_file():
        sys.path.insert(0, str(candidate))
        break

import tkinter as tk
from tkinter import ttk
import tkwin11 as UI


def main():
    UI.enable_dpi_awareness()
    root = tk.Tk()
    root.title({title!r})
    root.geometry("1000x700")
    UI.apply_theme(root)
    UI.configure_fluent(root)

    page = UI.FluentPage(root)
    page.pack(fill="both", expand=True)
    frame = ttk.Frame(page.body)
    frame.pack(fill="both", expand=True)
{body}
    root.mainloop()


if __name__ == "__main__":
    main()
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate a TkWebUI/TkWin11 starter")
    parser.add_argument("--style", choices=["web", "win11"], required=True)
    parser.add_argument("--kind", choices=sorted(COMMON), default="blank")
    parser.add_argument("--output", "-o", default="app.py")
    parser.add_argument("--title", default=None)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    target = Path(args.output)
    if target.exists() and not args.force:
        raise SystemExit(f"{target} 已存在；加 --force 覆盖")
    spec = COMMON[args.kind]
    title = args.title or spec["title"]
    body = spec["body"].replace("{style}", "TkWebUI" if args.style == "web" else "TkWin11")
    code = web_code(title, body) if args.style == "web" else win11_code(title, body)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(code, encoding="utf-8")
    print(f"已生成 {target}（{args.style} / {args.kind}）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
